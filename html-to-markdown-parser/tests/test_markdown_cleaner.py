"""
Tests for the markdown cleaner functionality.
"""
import pytest
from html_to_md.markdown_cleaner import clean_markdown


def test_trailing_whitespace_removal():
    """Test that trailing whitespace is removed from each line."""
    markdown = "Line with spaces    \nAnother line\t \nNo trailing space"
    expected = "Line with spaces\nAnother line\nNo trailing space"
    
    assert clean_markdown(markdown) == expected


def test_consecutive_newlines():
    """Test that 3+ consecutive newlines are replaced with 2 newlines."""
    markdown = "First paragraph\n\n\n\nSecond paragraph\n\n\nThird paragraph"
    expected = "First paragraph\n\nSecond paragraph\n\nThird paragraph"
    
    assert clean_markdown(markdown) == expected


def test_decorative_line_removal():
    """Test that purely decorative lines (-, *, |) are removed."""
    markdown = "Header\n----\nContent\n*****\nMore content\n|\n|\n|"
    expected = "Header\nContent\nMore content"
    
    assert clean_markdown(markdown) == expected


def test_malformed_list_collapse():
    """Test that malformed list items are collapsed correctly."""
    markdown = "- \nFirst item\n* \nSecond item\n+ \nThird item"
    expected = "- First item\n* Second item\n+ Third item"
    
    assert clean_markdown(markdown) == expected


def test_table_trailing_pipe_removal():
    """Test that unnecessary trailing pipes in tables are removed."""
    markdown = """
| Column A | Column B | Column C |
| --- | --- | --- |
| Data A1 | Data B1 | Data C1 |
| Data A2 | Data B2 |  |
"""
    expected = """
| Column A | Column B | Column C
| --- | --- | ---
| Data A1 | Data B1 | Data C1
| Data A2 | Data B2 |"""
    
    result = clean_markdown(markdown)
    # Compare line by line for better debugging
    result_lines = result.splitlines()
    expected_lines = expected.splitlines()
    
    # Debug information before assert
    print("\nResult lines:", result_lines)
    print("Expected lines:", expected_lines)
    print("Line counts:", len(result_lines), len(expected_lines))
    
    assert len(result_lines) == len(expected_lines)
    for i in range(len(expected_lines)):
        assert result_lines[i].rstrip() == expected_lines[i].rstrip()


def test_heading_separation():
    """Test that headings are properly separated with newlines."""
    markdown = "# Heading 1\nContent\n## Heading 2\nMore content\n### Heading 3\nEven more"
    expected = "# Heading 1\n\nContent\n## Heading 2\n\nMore content\n### Heading 3\n\nEven more"
    
    assert clean_markdown(markdown) == expected


def test_boilerplate_removal():
    """Test that repeated boilerplate lines are removed."""
    markdown = """Content
Footer: Generated by System
More content
Footer: Generated by System
Another paragraph
Footer: Generated by System
Last part
Footer: Generated by System"""

    expected = """Content
Footer: Generated by System
More content
Another paragraph
Last part"""
    
    assert clean_markdown(markdown) == expected


def test_empty_input():
    """Test handling of empty input."""
    assert clean_markdown("") == ""
    assert clean_markdown(None) == ""


def test_comprehensive_cleaning():
    """Test all cleaning features together on a complex markdown example."""
    markdown = """# Document Title    
    
    

## Section 1   
Content with trailing spaces    
- 
First list item
*    
Second list item    
    
----

| Column 1 | Column 2 | Column 3 |
| --- | --- | --- |
| Data 1 | Data 2 | Data 3 |
| More data | More info |  |

### Subsection    
Text here

***

Repeated footer line
More content

Repeated footer line

Final paragraph
Repeated footer line"""

    # Process and debug
    result = clean_markdown(markdown)
    print("\nComprehensive test result:")
    print(repr(result))
    
    expected = """# Document Title

## Section 1

Content with trailing spaces
- First list item
* Second list item

| Column 1 | Column 2 | Column 3
| --- | --- | ---
| Data 1 | Data 2 | Data 3
| More data | More info |

### Subsection

Text here

Repeated footer line
More content

Final paragraph"""
    
    # Compare line by line
    result_lines = result.splitlines()
    expected_lines = expected.splitlines()
    
    assert len(result_lines) == len(expected_lines), f"Line count mismatch: {len(result_lines)} vs {len(expected_lines)}"
    for i in range(len(expected_lines)):
        assert result_lines[i].rstrip() == expected_lines[i].rstrip(), f"Line {i+1} mismatch: '{result_lines[i]}' vs '{expected_lines[i]}'" 